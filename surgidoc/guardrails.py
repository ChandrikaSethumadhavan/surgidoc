"""FR-7, NFR-5: deterministic guardrails between the judge and the human reviewer.

Schema validation (Pydantic), content-safety policy, output validation, draft labelling. Rules are regex heuristics on
normalised English text, not an LLM, so they cannot be argued around. They are a safety net, not a clinical guarantee:
the human approval gate is the real control. Violations never echo the matched text (it may be a secret or personal data).
"""
import re
import unicodedata
from dataclasses import dataclass, field
from typing import Annotated

from pydantic import BaseModel, Field, StringConstraints, ValidationError

DISCLAIMER = ("DRAFT - generated by an AI assistant for clinician review. It is not a diagnosis and must be reviewed, "
              "edited and approved by a clinician before use.")

_I = re.I
POLICY = {
    "diagnosis": [r"\bpatient (has|had|suffers? from|is suffering from)\b", r"\bsuffers? from\b", r"\bconsistent with\b",
                  r"\bconfirms?\b", r"\bdiagnos(is|ed|e)\b", r"\bdiagnostic of\b",
                  r"\bis (a|an) (malignant|carcinoma|cancer|adenocarcinoma)\b",
                  r"\b(is|are|was|were) (cancerous|malignant|benign|neoplastic)\b", r"\bpoints? to\b",
                  r"\b(likely|probably) (shows?|represents?|reflects?|is|are)\b", r"\bindicative of\b"],
    "treatment": [r"\bprescrib\w*", r"\badminister\w*", r"\bpatient (should|must|needs? to|ought to)\b",
                  r"\bshould be (treated|given|started|administered|prescribed|put on)\b",
                  r"\b\d+(\.\d+)?\s?(mg|mcg|ug|ml|g|iu)\b", r"\b(once|twice|three times) (a |per )?(day|daily)\b"],
    "injection": [r"ignore (all |any |the |your )?(previous |prior |above )?(instructions|rules|guidelines|constraints)",
                  r"disregard (the |all |any |your )?(previous |prior |above )?(system prompt|instructions)",
                  r"system prompt", r"<\s*/?\s*source\b", r"\bas an ai( language model)?\b"],
    "sensitive": [r"aiza[0-9a-z_\-]{35}", r"\bpa-[0-9a-z_\-]{30,}", r"\bgh[pousr]_[0-9a-z]{36,}",
                  r"-----begin [a-z ]*private key-----", r"[a-z0-9._%+\-]+@[a-z0-9.\-]+\.[a-z]{2,}",
                  r"(?<!\w)(\+\d[\d\s\-()]{7,}\d|\(?\d{3,5}\)?[\s\-]\d{6,8})(?!\w)",
                  r"\b(dob|date of birth|born on)\b", r"\b(mrn|medical record( number)?|patient id)\b"],
}
_ZERO_WIDTH = dict.fromkeys(map(ord, "​‌‍‎‏⁠﻿­"))
_COMPILED = {rule: [re.compile(p, _I) for p in pats] for rule, pats in POLICY.items()}

SourceId = Annotated[str, StringConstraints(pattern=r"^[FK]\d+$")]


class StatementModel(BaseModel):
    text: Annotated[str, StringConstraints(min_length=1, max_length=1000)]
    sources: Annotated[list[SourceId], Field(min_length=1)]


class ReportModel(BaseModel):
    statements: Annotated[list[StatementModel], Field(min_length=1, max_length=50)]


@dataclass(frozen=True)
class Violation:
    rule: str
    statement: int | None
    detail: str


@dataclass
class GuardrailResult:
    passed: bool
    violations: list = field(default_factory=list)


def _normalise(text):
    return " ".join(unicodedata.normalize("NFKC", text).translate(_ZERO_WIDTH).casefold().split())


def check_report(report, extra_blocked=None):
    """extra_blocked: {rule_name: regex} added to the policy for this call."""
    v = []
    if report.status != "approved":
        v.append(Violation("status", None, f"report status is {report.status!r}, only judge-approved drafts pass"))
    if report.draft is not True:
        v.append(Violation("draft", None, "report is not flagged as a draft"))
    try:
        ReportModel.model_validate({"statements": [{"text": s.text, "sources": s.sources} for s in report.statements]})
    except ValidationError as e:  # location + message only: pydantic's input echo is dropped
        for err in e.errors(include_input=False, include_url=False):
            loc = err["loc"]
            v.append(Violation("schema", loc[1] if len(loc) > 1 and isinstance(loc[1], int) else None,
                               f"{'.'.join(map(str, loc))}: {err['msg']}"))
    for i, s in enumerate(report.statements):
        for src in s.sources:
            if re.fullmatch(r"[FK]\d+", src) and src not in report.sources:
                v.append(Violation("citation", i, "cites a source id that is not in the report sources"))
    compiled = dict(_COMPILED)
    for rule, pattern in (extra_blocked or {}).items():
        compiled[rule] = [re.compile(pattern, _I)]
    for i, s in enumerate(report.statements):
        text = _normalise(s.text)
        for rule, patterns in compiled.items():
            if any(p.search(text) for p in patterns):
                v.append(Violation(rule, i, f"statement matches the '{rule}' policy"))
    return GuardrailResult(not v, v)


def label_draft(report, result):
    """Only a report that passed check_report can be labelled for human review."""
    if not result.passed:
        raise ValueError("report did not pass the guardrails")
    return {"status": "DRAFT", "disclaimer": DISCLAIMER,
            "statements": [{"text": s.text, "sources": list(s.sources)} for s in report.statements],
            "sources": {k: dict(x) for k, x in report.sources.items()}}
